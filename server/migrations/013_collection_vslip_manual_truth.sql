-- 把「人工在后台改过的 collection 竖签」固化成迁移，让新建库
-- 跑完迁移后与现有库**完全一致**（而不是停在 008 的中间口径）。
--
-- 背景（2026-10-03 核对）：
--   collection.vslip_cn（右上竖签）历经三版：
--     ① 002_seed      →'新中式 · 嫁衣'   / '西式 · 美学'
--     ② 008（10-02 拍板）→ '东方 · 新韵'   / '西式 · 美学'
--     ③ 后台人工编辑   → **'中式 · 美学'** / '西式 · 美学'← 本迁移采用
--   现状：DB 里 chinese 是「中式 · 美学」，而 008 写的是「东方 · 新韵」，
--   两者不一致。若不固化，**新建库跑完 008 会停在「东方 · 新韵」**，
--   与现有库分叉。
--
-- 口径归属：**以人工后台改的值为准**（用户 2026-10-03 拍板）。
--   这条原则同时解释了为什么 admin后台保留 vslipCn 编辑入口 ——
--   竖签是「可运营文案」，允许覆盖seed 口径；迁移只负责把最终态固定下来。
--
-- 本迁移只改 vslip_cn 一个字段（纯文案），不动 style / big_cn / enabled / show_big。
--
-- 幂等：纯 UPDATE，重复执行结果一致。
-- ============================================================

-- ① 中式：008 写的是「东方 · 新韵」，人工后台改成「中式 · 美学」→ 固化人工值
UPDATE collection SET vslip_cn = '中式 · 美学' WHERE style = 'chinese';

-- ② 西式：008 已把「西式 · 浪漫」改成「西式 · 美学」，与人工值一致；
--    这里显式重述一次，保证新建库 / 被改过的库都能收敛到同一口径。
UPDATE collection SET vslip_cn = '西式 · 美学' WHERE style = 'western';
