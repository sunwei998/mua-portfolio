#!/usr/bin/env bash
# ============================================================================
# 予时妍 YUÉ ATELIER ·【已退休 2026-10-03】上传素材同步脚本
#
# 保留这个文件只为记录「为什么曾经需要它、现在为什么不需要」，不要再调用。
#
# ---- 历史：命名卷方案下为什么需要同步 --------------------------------------
#   后台上传的图/视频写进命名卷 mua_uploads_assets，而宿主 Nginx 托管的静态根
#   是 /opt/mua/site —— 容器卷里的文件 Nginx 读不到。
#   于是每次部署后要把卷里的内容 rsync 出来到 /opt/mua/site/img/uploads。
#   同步没跑 ⇒ 前台图片 404，且日志里什么线索都没有（最难查的一类故障）。
#
# ---- 现在：bind mount 取代命名卷，同步不再需要 ----------------------------
#   deploy/docker-compose.yml 改成
#       /opt/mua/site/img/uploads : /site/img/uploads
#   API 写入与 Nginx 读取落在**同一个宿主目录**：
#     · 容器可写（uid 1000 对宿主目录的权限由 update.sh 首次部署时 chown 保证）
#     · 宿主 Nginx 直接可读
#     · 容器重建/换镜像都不影响素材（在宿主盘上）
#   一层介质、一个真相来源，"忘了同步" 这类故障从根上消失。
#
# ---- 如果你又需要它，说明 compose 被改回了命名卷 ----------------------------
#   先确认 server/src/admin.ts 的 UPLOAD_DIR 解析到哪：
#     镜像里 /app/src/admin.ts ⇒ /app/src/../../site/img/uploads ⇒ /site/img/uploads
#   挂载点必须与它一致，且 node 用户（uid 1000）对该目录有写权限。
# ============================================================================
echo "sync-uploads.sh 已退休：uploads 现为 bind mount，无需同步。"
echo "（本脚本保留仅为记录历史决策，见文件头注释）"
exit 0
